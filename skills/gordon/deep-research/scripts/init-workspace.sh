#!/usr/bin/env bash
# init-workspace.sh — 初始化深度研究工作区
#
# 用法:
#   init-workspace.sh <研究主题> [目标目录]
#
# 示例:
#   init-workspace.sh "Rust 还是 Go 做后端" /path/to/project
#
# 在目标目录下创建 deep-research-<主题>-<YYYYMMDD>/，
# 并一次性生成 00–05 六个骨架文件（字段与表头已预填）。
set -euo pipefail

TOPIC="${1:-}"
DEST="${2:-.}"

if [[ -z "$TOPIC" ]]; then
  echo "用法: $0 <研究主题> [目标目录]" >&2
  echo "示例: $0 \"Rust 还是 Go 做后端\" /path/to/project" >&2
  exit 1
fi

# 主题转安全目录名（保留中文，仅把空白与路径分隔符换成连字符）
SLUG="$(printf '%s' "$TOPIC" \
  | sed 's/[[:space:]\/\\]\+/-/g' \
  | sed 's/-\+/-/g; s/^-//; s/-$//')"
[[ -z "$SLUG" ]] && SLUG="research"

DATE="$(date +%Y%m%d)"
NOW="$(date '+%Y-%m-%d %H:%M %Z')"

WS_DIR="${DEST%/}/deep-research-${SLUG}-${DATE}"
mkdir -p "$WS_DIR"

# ---- 00-研究简报 ----
cat > "$WS_DIR/00-研究简报.md" <<EOF
# 00-研究简报

- 研究目标：[待填]
- 研究对象：${TOPIC}
- 受众：[待填]
- 范围与边界：[待填]
- 关键定义：[待填]
- 假设：[待填]
- 非目标与限制：[待填]
- 交付标准：[待填]
EOF

# ---- 01-研究问题 ----
cat > "$WS_DIR/01-研究问题.md" <<'EOF'
# 01-研究问题

| ID | 类型 | 研究问题 | 结论意义 | 所需证据/指标 | 完成标准 | 优先级 | 状态 | 简答 |
|---|---|---|---|---|---|---|---|---|
| Q1 | [拆解维度] | [待填] | [待填] | [待填] | [待填] | P0 | 待开始 | 待研究 |
EOF

# ---- 02-检索方案 ----
cat > "$WS_DIR/02-检索方案.md" <<'EOF'
# 02-检索方案

### Q1：[问题]

- 取证目标：[待填]
- 数据字段：[待填]
- 核心/同义/英文/排除词：[待填]
- 查询式：[待填]
- 优先与备用来源：[待填]
- 交叉验证：[待填]
- 停止条件：[待填]
EOF

# ---- 03-研究报告 ----
cat > "$WS_DIR/03-研究报告.md" <<'EOF'
# 03-研究报告

### 1. 执行摘要与结论

- 当前结论：待研究
- 证据与分析：待填
- 局限/反证：待填
- 待补数据：待填

### 2. 研究范围、定义和方法
### 3. [主题主体内容（按研究问题组织）]
### 4. 关键证据与分析
### 5. 风险、局限与反证
### 6. 结论、建议与下一步
### 7. 来源与附录
EOF

# ---- 04-执行清单 ----
cat > "$WS_DIR/04-执行清单.md" <<EOF
# 04-执行清单

当前焦点：待定
下一步：定义研究问题（阶段 1）
最近更新：${NOW}
整体状态：规划中

| 任务ID | 问题ID | 动作 | 产物 | 状态 | 证据门槛 | 依赖/阻塞 | 下一动作 |
|---|---|---|---|---|---|---|---|
| T01 | Q1 | [待填] | [待填] | 待开始 | [待填] | 无 | [待填] |
EOF

# ---- 05-证据台账 ----
cat > "$WS_DIR/05-证据台账.md" <<'EOF'
# 05-证据台账

| E-ID | Q-ID | 主张/数据 | 来源标题 | 机构/作者 | 发布日期 | 访问日期 | URL/文件 | 类型 | 范围/口径 | 可信度 | 支持/反驳 | 报告落点 | 备注 |
|---|---|---|---|---|---|---|---|---|---|---|---|---|---|
EOF

echo "已创建研究工作区：${WS_DIR}"
echo "生成文件：00-研究简报 / 01-研究问题 / 02-检索方案 / 03-研究报告 / 04-执行清单 / 05-证据台账"
echo "下一步：进入阶段 1，定义研究问题并写入 01-研究问题.md。"
